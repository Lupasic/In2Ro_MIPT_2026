"""SOURCES.md — the generated index of local source documents.

The citation column is written for LaTeX, not for Markdown: assemble_deck.py pastes
it verbatim into an \\item of the Reference Materials frame. Author and topic only.
"""
import hashlib
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

from . import paths

PREFIXES = {
    "De_Luca": "DL",
    "Klimchick": "KL",
    "Skillbox": "SB",
    "Siegwart": "SW",
    "HWs": "AH",
    "Bulichev": "OB",
}

AUTHORS = {
    "DL": "A. De Luca",
    "KL": "A. Klimchik",
    "SB": "Skillbox",
    "SW": "Siegwart, Nourbakhsh, Scaramuzza",
    "AH": "A. De Luca",
    "OB": "O. Bulichev",
}

INDEXED_SUFFIXES = {".pdf", ".pptx", ".ipynb", ".docx", ".md"}

HEADER = "| handle | file | pages | citation | sha256 |"
DIVIDER = "|---|---|---:|---|---|"

PREAMBLE = """# Sources

Generated by `python tools/index_sources.py`. The source files themselves are not in
git; `python tools/check_sources.py` verifies a local copy against the hashes below.

Pages are physical PDF-viewer pages counted from 1. A dash means the format is not
paginated. The citation column is hand-edited LaTeX — author and topic, never page
numbers — and reindexing preserves it.
"""


@dataclass(frozen=True)
class Source:
    handle: str
    path: str
    pages: str
    citation: str
    sha256: str


CYRILLIC = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def transliterate(text: str) -> str:
    """Cyrillic to Latin, so a Russian filename yields a readable ASCII handle."""
    out = []
    for ch in text:
        lower = ch.lower()
        if lower in CYRILLIC:
            latin = CYRILLIC[lower]
            out.append(latin.capitalize() if ch != lower and latin else latin)
        else:
            out.append(ch)
    return "".join(out)


def slug(stem: str) -> str:
    return re.sub(r"[^0-9A-Za-z]+", "_", transliterate(stem)).strip("_")


def handle_for(rel_path: str) -> str:
    parts = rel_path.split("/")
    if len(parts) < 3 or parts[0] != "sources":
        raise ValueError(f"{rel_path}: expected sources/<collection>/<file>")
    prefix = PREFIXES.get(parts[1])
    if prefix is None:
        raise ValueError(
            f"{rel_path}: no handle prefix for collection {parts[1]!r}; "
            f"known collections are {sorted(PREFIXES)}"
        )
    return f"{prefix}_{slug(Path(rel_path).stem)}"


def seed_citation(handle: str, rel_path: str) -> str:
    author = AUTHORS[handle.split("_", 1)[0]]
    topic = slug(Path(rel_path).stem).replace("_", " ")
    return f"{author} --- {topic}"


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_sources_md(md_path=None) -> dict[str, Source]:
    md_path = Path(md_path) if md_path else paths.sources_md()
    index: dict[str, Source] = {}
    if not md_path.exists():
        return index
    for line in md_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line.startswith("|") or line == HEADER or set(line) <= set("|-: "):
            continue
        raw = line.strip("|").split("|")
        if len(raw) < 5:
            raise ValueError(f"{md_path}: table row has too few columns: {line}")
        if len(raw) > 5:
            # The citation is hand-edited LaTeX and may contain a literal "|".
            raw = raw[:3] + ["|".join(raw[3:-1])] + raw[-1:]
        cells = [cell.strip() for cell in raw]
        handle, file_cell, pages, citation, digest = cells
        source = Source(handle.strip("`"), file_cell.strip("`"), pages, citation, digest.strip("`"))
        index[source.handle] = source
    return index


def render_sources_md(sources: Iterable[Source]) -> str:
    rows = [f"| `{s.handle}` | `{s.path}` | {s.pages} | {s.citation} | `{s.sha256}` |"
            for s in sorted(sources, key=lambda s: s.path)]
    return "\n".join([PREAMBLE, HEADER, DIVIDER, *rows, ""])


def write_sources_md(sources: Iterable[Source], md_path=None) -> None:
    md_path = Path(md_path) if md_path else paths.sources_md()
    md_path.write_text(render_sources_md(sources), encoding="utf-8", newline="\n")
